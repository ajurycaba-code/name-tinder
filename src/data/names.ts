function slugify(text: string) {
  return text
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function build(list: Raw[], gender: Gender): NameEntry[] {
  return list.map(([name, origin, meaning, fact], index) => ({
    id: `${gender.toLowerCase()}-${slugify(name)}`,
    name,
    gender,
    rank: index + 1,
    origin,
    meaning,
    fact,
  }))
}

